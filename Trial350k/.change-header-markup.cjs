const fs = require('node:fs');
const file = 'index.html';
let html = fs.readFileSync(file, 'utf8');
const bookMarkup = '<a class="header-book" href="#book">Book appointment ';
if (!html.includes(bookMarkup)) throw new Error('Book link markup not found');
html = html.replace(bookMarkup, '<a class="header-book" href="#book" aria-label="Book appointment"><span class="book-label">Book appointment</span> ');
const menuMarkup = /<button class="menu-toggle" aria-label="Open menu" aria-expanded="false" aria-controls="navigation">Menu <span>[\s\S]*?<\/span><\/button>/;
if (!menuMarkup.test(html)) throw new Error('Menu button markup not found');
html = html.replace(menuMarkup, '<button class="menu-toggle" type="button" aria-label="Open menu" aria-expanded="false" aria-controls="navigation"><span class="menu-icon" aria-hidden="true"><i></i><i></i></span><span class="menu-label">Menu</span></button>');
fs.writeFileSync(file, html, 'utf8');
